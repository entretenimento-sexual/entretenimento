export type CommunityPublicErrorReason =
  (typeof COMMUNITY_PUBLIC_ERROR_REASONS)[number];

const COMMUNITY_PUBLIC_ERROR_REASON_SET: ReadonlySet<string> =
  new Set(COMMUNITY_PUBLIC_ERROR_REASONS);

export function isCommunityPublicErrorReason(
  value: unknown
): value is CommunityPublicErrorReason {
  return typeof value === 'string'
    && COMMUNITY_PUBLIC_ERROR_REASON_SET.has(value);
}
