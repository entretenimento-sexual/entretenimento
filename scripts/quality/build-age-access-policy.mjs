import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const root = path.resolve(__dirname, '..', '..');
const manifestPath = path.join(root, 'config', 'age-access-policy.json');
const checkOnly = process.argv.includes('--check');

const frontendTarget = path.join(
  root,
  'src',
  'app',
  'core',
  'services',
  'compliance',
  'age-access-policy.generated.ts'
);
const functionsTarget = path.join(
  root,
  'functions',
  'src',
  'compliance',
  'age-access-policy.generated.ts'
);
const rulesTarget = path.join(
  root,
  'firestore-rules',
  '_age_access_policy.generated.rules'
);

const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
const version = Number(manifest?.version);
const mode = String(manifest?.mode ?? '').trim().toUpperCase();
const allowSelfDeclaration = manifest?.allowSelfDeclaration === true;

if (!Number.isInteger(version) || version < 1) {
  throw new Error('age-access-policy.version precisa ser inteiro positivo.');
}

if (!['DECLARATION_FIRST', 'VERIFIED_ONLY'].includes(mode)) {
  throw new Error('age-access-policy.mode inválido.');
}

if ((mode === 'DECLARATION_FIRST') !== allowSelfDeclaration) {
  throw new Error(
    'age-access-policy.allowSelfDeclaration deve refletir o modo canônico.'
  );
}

function normalize(value) {
  return String(value ?? '').replace(/\r\n?/g, '\n');
}

function renderTs() {
  return `// AUTO-GENERATED by scripts/quality/build-age-access-policy.mjs
// Source of truth: config/age-access-policy.json
// Do not edit manually.

export const AGE_ACCESS_POLICY_VERSION = ${version} as const;
export const AGE_ACCESS_MODE = '${mode}' as const;
export const AGE_ACCESS_ALLOWS_SELF_DECLARATION = ${allowSelfDeclaration} as const;
`;
}

function renderRules() {
  return `// AUTO-GENERATED by scripts/quality/build-age-access-policy.mjs
// Source of truth: config/age-access-policy.json
// Do not edit manually.

function ageAccessPolicyAllowsSelfDeclaration() {
  return ${allowSelfDeclaration ? 'true' : 'false'};
}
`;
}

function writeOrCheck(target, expected) {
  if (checkOnly) {
    const current = fs.existsSync(target)
      ? fs.readFileSync(target, 'utf8')
      : '';

    if (normalize(current) !== normalize(expected)) {
      throw new Error(
        `Política etária gerada está desatualizada: ${path.relative(root, target)}`
      );
    }
    return;
  }

  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, expected, 'utf8');
}

const ts = renderTs();
writeOrCheck(frontendTarget, ts);
writeOrCheck(functionsTarget, ts);
writeOrCheck(rulesTarget, renderRules());

console.log(
  checkOnly
    ? '[age-access-policy] Frontend, Functions e Rules sincronizados.'
    : '[age-access-policy] Artefatos gerados.'
);
