import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..', '..');
const manifestPath = path.join(repoRoot, 'config', 'community-contracts.json');
const checkOnly = process.argv.includes('--check');
const frontendTarget = path.join(repoRoot, 'src', 'app', 'community', 'data-access', 'community-contract.generated.ts');
const functionsTarget = path.join(repoRoot, 'functions', 'src', 'community', 'community-contract.generated.ts');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));

function normalizeLineEndings(value) {
  return String(value ?? '').replace(/\r\n?/g, '\n');
}

function normalizeLiteralList(value, label) {
  if (!Array.isArray(value) || value.length === 0) throw new Error(`${label} precisa ser uma lista não vazia.`);
  const normalized = value.map((item) => String(item ?? '').trim());
  for (const item of normalized) {
    if (!/^[a-z][a-z0-9_]{1,63}$/.test(item)) throw new Error(`${label} contém valor inválido: ${item}`);
  }
  if (new Set(normalized).size !== normalized.length) throw new Error(`${label} contém valores duplicados.`);
  return normalized;
}

const sourceTypes = normalizeLiteralList(manifest.sourceTypes, 'sourceTypes');
const joinPolicies = normalizeLiteralList(manifest.joinPolicies, 'joinPolicies');
const viewerRoles = normalizeLiteralList(manifest.viewerRoles, 'viewerRoles');
const viewerModes = normalizeLiteralList(manifest.viewerModes, 'viewerModes');
const lifecycleStatuses = normalizeLiteralList(manifest.lifecycleStatuses, 'lifecycleStatuses');

